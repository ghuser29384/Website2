    def postgres_persistence_enabled(self) -> bool:
        if self.persistence_provider == "postgres":
            return True
        if self.persistence_provider == "memory":
            return False
        return self.app_env != "local" and bool(self.database_url)

    def data_use_scope_allowed(self) -> bool:
        return self.community_notes_data_use_purpose == "community_notes_ai_note_writing"

    def operational_evals_scope_allowed(self) -> bool:
        return self.operational_evals_directly_necessary and self.data_use_scope_allowed()

    def bot_identity_configured(self) -> bool:
        if not self.require_bot_identity_disclosure:
            return True
        return bool(self.bot_profile_disclosure.strip()) and bool(self.bot_responsible_party.strip())

    def policy_scope(self) -> dict:
        return {
            "community_notes_data_use_purpose": self.community_notes_data_use_purpose,
            "data_use_scope_allowed": self.data_use_scope_allowed(),
            "operational_evals_directly_necessary": self.operational_evals_directly_necessary,
            "operational_evals_scope_allowed": self.operational_evals_scope_allowed(),
            "policy_text": (
                "Process X Community Notes API data solely for Community Notes AI note writing. "
                "Run evaluation only when directly necessary to operate that note-writing workflow."
            ),
        }

    def bot_identity(self) -> dict:
        return {
            "required": self.require_bot_identity_disclosure,
            "configured": self.bot_identity_configured(),
            "profile_disclosure": self.bot_profile_disclosure,
            "responsible_party": self.bot_responsible_party,
        }

    def x_oauth2_refresh_configured(self) -> bool:
        return bool(self.x_oauth2_client_id and self.x_oauth2_refresh_token)

    def x_live_credentials_configured(self) -> bool:
        return bool(self.x_bearer_token) or self.x_oauth2_refresh_configured()

